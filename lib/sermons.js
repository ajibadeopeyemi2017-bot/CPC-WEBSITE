// Fallback stream for demonstration/testing. Replace any sermon's audioUrl with your real MP3 link.
const DEMO_AUDIO_URL = 'https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3';

// AudioPlayerBar (mounted in the root layout) listens for this event.
export function playSermon(sermon) {
  if (typeof window !== 'undefined') {
    window.dispatchEvent(
      new CustomEvent('play-cpc-sermon', {
        detail: {
          id: sermon.id,
          title: sermon.title,
          minister: sermon.minister,
          category: sermon.category,
          scripture: sermon.scripture,
          duration: sermon.duration,
          audioUrl: sermon.audioUrl || DEMO_AUDIO_URL,
          mode: 'sermon',
        },
      })
    );
  }
}

export function playLiveMixlr() {
  if (typeof window !== 'undefined') {
    window.dispatchEvent(
      new CustomEvent('play-cpc-sermon', {
        detail: {
          id: 'live-broadcast',
          title: 'Sunday / Midweek Live Service',
          minister: 'Apostle Oluwafunminiyi Olufisayo',
          category: 'Live Broadcast',
          mode: 'mixlr',
        },
      })
    );
  }
}
