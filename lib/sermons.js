// Format seconds into HH:MM:SS or MM:SS
export function formatAudioTime(seconds) {
  if (isNaN(seconds) || seconds === null || seconds < 0) return '0:00';
  const s = Math.floor(seconds);
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = s % 60;

  if (hrs > 0) {
    return `${hrs}:${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
  }
  return `${mins}:${String(secs).padStart(2, '0')}`;
}

// LocalStorage helpers for audio playback resume
export function getSavedPlaybackPosition(sermonId) {
  if (typeof window === 'undefined' || !sermonId) return null;
  try {
    const raw = localStorage.getItem(`cpc_sermon_pos_${sermonId}`);
    if (!raw) return null;
    const parsed = parseFloat(raw);
    return isNaN(parsed) ? null : parsed;
  } catch {
    return null;
  }
}

