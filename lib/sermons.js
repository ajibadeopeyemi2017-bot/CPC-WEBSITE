/**
 * Retrieves a single sermon by its slug or id
 */
export function getSermonBySlug(slug) {
  if (!slug) return SERMONS[0];
  const normalized = slug.toLowerCase().trim();
  return SERMONS.find((s) => s.id === normalized || s.slug === normalized) || SERMONS[0];
}

/**
 * Retrieves related sermons in the same category or series
 */
export function getRelatedSermons(currentSermon, limit = 3) {
  if (!currentSermon) return SERMONS.slice(0, limit);
  const matches = SERMONS.filter(
    (s) =>
      s.id !== currentSermon.id &&
      (s.category === currentSermon.category || s.series === currentSermon.series)
  );
  if (matches.length >= limit) return matches.slice(0, limit);
  const others = SERMONS.filter(
    (s) => s.id !== currentSermon.id && !matches.some((m) => m.id === s.id)
  );
  return [...matches, ...others].slice(0, limit);
}

