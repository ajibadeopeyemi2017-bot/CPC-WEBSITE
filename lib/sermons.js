// LocalStorage helpers for saved/bookmarked sermons
export function getBookmarkedSermonIds() {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem('cpc_bookmarked_sermons');
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function toggleBookmarkSermon(sermonId) {
  if (typeof window === 'undefined' || !sermonId) return false;
  try {
    const current = getBookmarkedSermonIds();
    const exists = current.includes(sermonId);
    const updated = exists ? current.filter((id) => id !== sermonId) : [...current, sermonId];
    localStorage.setItem('cpc_bookmarked_sermons', JSON.stringify(updated));
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('cpc:bookmarks-changed', { detail: { sermonId, isBookmarked: !exists } }));
    }
    return !exists;
  } catch {
    return false;
  }
}

export function isSermonBookmarked(sermonId) {
  if (typeof window === 'undefined' || !sermonId) return false;
  const list = getBookmarkedSermonIds();
  return list.includes(sermonId);
}

// Clean filename generator for MP3 download
export function getSermonDownloadFilename(sermon) {
  const cleanTitle = (sermon.title || 'cpc-sermon')
    .replace(/[^\w\s-]/gi, '')
    .trim()
    .replace(/\s+/g, '-');
  return `CPC-${cleanTitle}.mp3`;
}

// Download helper with fallback for CORS/cross-origin audio assets
export async function downloadSermonAudio(sermon) {
  const audioUrl = sermon.audioUrl || DEMO_AUDIO_URL;
  const filename = getSermonDownloadFilename(sermon);

  try {
    // Attempt blob download first for seamless in-browser save
    const response = await fetch(audioUrl, { mode: 'cors' });
    if (!response.ok) throw new Error('Direct fetch failed');
    const blob = await response.blob();
    const blobUrl = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = blobUrl;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(() => URL.revokeObjectURL(blobUrl), 30000);
    return true;
  } catch {
    // Fallback: trigger standard browser download via anchor
    const a = document.createElement('a');
    a.href = audioUrl;
    a.download = filename;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    return false;
  }
}

